/**
 * Regenerate src/data/languages.js from the afriso dataset.
 *
 *   node scripts/build-languages.mjs
 *
 * afriso (github.com/AfriSpeech/afriso) is the source of truth for African
 * language codes, names, and the countries each is spoken in. This pulls the
 * living languages out of it and writes a compact table the join form can ship
 * to the browser.
 */

import { writeFile } from 'node:fs/promises';

const BASE = 'https://raw.githubusercontent.com/AfriSpeech/afriso/main/src/afriso/data';
const OUT = new URL('../src/data/languages.js', import.meta.url);

/** Minimal CSV reader: handles quoted fields and doubled quotes. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;

  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i += 1; } else { quoted = false; }
      } else {
        field += c;
      }
    } else if (c === '"') {
      quoted = true;
    } else if (c === ',') {
      row.push(field); field = '';
    } else if (c === '\n') {
      row.push(field); rows.push(row); row = []; field = '';
    } else if (c !== '\r') {
      field += c;
    }
  }
  if (field || row.length) { row.push(field); rows.push(row); }

  const [header, ...body] = rows;
  return body
    .filter((r) => r.length === header.length)
    .map((r) => Object.fromEntries(header.map((h, i) => [h, r[i]])));
}

async function fetchCsv(name) {
  const res = await fetch(`${BASE}/${name}`);
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  return parseCsv(await res.text());
}

const [languages, countries] = await Promise.all([
  fetchCsv('languages.csv'),
  fetchCsv('countries.csv'),
]);

const countryNames = Object.fromEntries(
  countries.map((c) => [c.code2, c.name]).sort(([a], [b]) => a.localeCompare(b)),
);

// Living languages only: nobody is building for an extinct one, and dropping
// them keeps the payload down.
const rows = languages
  .filter((l) => l.type === 'living' && l.iso639_3 && l.name)
  .map((l) => [l.iso639_3, l.name, l.countries || ''])
  .sort((a, b) => a[1].localeCompare(b[1], 'en'));

const banner = `// GENERATED by scripts/build-languages.mjs - do not edit by hand.
// Source: github.com/AfriSpeech/afriso (${rows.length} living languages).
`;

const body = `${banner}
/** ISO 3166-1 alpha-2 to country name, for the countries afriso covers. */
export const COUNTRY_NAMES = ${JSON.stringify(countryNames, null, 2)};

/** Offered when someone is building for a language afriso does not list. */
export const OTHER_LANGUAGE = { code: 'other', name: 'Other / Not listed', countries: [] };

/**
 * [ISO 639-3 code, name, semicolon-joined ISO 3166-1 alpha-2 country codes],
 * sorted by name.
 */
const ROWS = ${JSON.stringify(rows)};

export const LANGUAGES = ROWS.map(([code, name, cc]) => ({
  code,
  name,
  countries: cc ? cc.split(';') : [],
}));

const BY_CODE = new Map(LANGUAGES.map((l) => [l.code, l]));

/** Resolve a submitted language code to its entry, or null if unknown. */
export function findLanguage(code) {
  const key = String(code || '').trim().toLowerCase();
  if (!key) return null;
  if (key === OTHER_LANGUAGE.code) return OTHER_LANGUAGE;
  return BY_CODE.get(key) || null;
}

/** Human-readable country list for a language, e.g. "Ghana; Togo". */
export function countryNamesFor(language) {
  if (!language) return '';
  return language.countries
    .map((c) => COUNTRY_NAMES[c] || c)
    .join('; ');
}
`;

await writeFile(OUT, body);
console.log(`Wrote ${rows.length} languages and ${Object.keys(countryNames).length} countries.`);
